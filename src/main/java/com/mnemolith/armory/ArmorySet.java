package com.mnemolith.armory;

/** Four wearable lines. Each one changes how the wearer meets memory, not only how hard a hit lands. */
public enum ArmorySet {
    /** Early cloth. Full set and a sneak: memory mobs lose the wearer, and walking leaves no path. */
    HUSH,
    /** Iron-weight plate paid for with scales from fracture stalkers. Slow, and it shrugs off monsters. */
    GRAVE,
    /** Lattice tuned to echoes. Full set reaches further when the lens possesses. */
    ECHO,
    /** Post-scar plate. In a fracture it hits harder and the chunk keeps paying instability. */
    SCAR
}
